"""Embeds the clean tables in data/base-data.js so the dashboard also works when opened from disk (file://), where
browsers block fetch() of local files. Run after clean_data.py:  python scripts/build_base_data.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLES = ["orders", "order_items", "reviews", "customers", "sellers", "products", "categories", "states", "calendar"]
CAL_COLS = ["date", "sales_event", "is_peak_logistics", "is_public_holiday", "holiday_name"]
data = {}
for t in TABLES:
    text = (ROOT / "data" / "clean" / f"{t}.csv").read_text(encoding="utf-8")
    if t == "calendar":   # only the columns the dashboard uses
        import csv, io
        rows = list(csv.DictReader(io.StringIO(text)))
        out = io.StringIO(); w = csv.DictWriter(out, CAL_COLS, extrasaction="ignore", lineterminator="\n"); w.writeheader(); w.writerows(rows); text = out.getvalue()
    data[t] = text
payload = {"name": "Marketvale marketplace data (synthetic), clean tables", "source": "marketvale_marketplace_data.xlsx, rebuilt from the raw sheets by scripts/clean_data.py",
           "extract": "2025-12-31 23:59", "tables": data}
(ROOT / "data" / "base-data.js").write_text("/* Generated by scripts/build_base_data.py - clean Marketvale tables (synthetic data). */\nwindow.BASE_DATASET = " + json.dumps(payload) + ";\n", encoding="utf-8")
print({t: v.count("\n") - 1 for t, v in data.items()}, "bytes", sum(len(v) for v in data.values()))
